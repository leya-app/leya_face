export function exSeconds(ex) {
  return ex.reps * (ex.hold + 3);
}

export function programMinutes(p) {
  const s = p.list.reduce((a, k) => a + exSeconds(EXERCISES[k]), 0);
  return Math.max(1, Math.round(s / 60));
}

export function countWord(n) {
  return n === 1 ? '1 упражнение' : `${n} упражнения`;
}
