export function massageSeconds(m) { return m.count * m.tempo; }
export function minutesOf(keys) {
  return Math.max(1, Math.round(keys.reduce((a, k) => a + massageSeconds(MASSAGES[k]) + 6, 0) / 60));
}

// ---------- геометрия ----------

export function quad(p0, p1, p2, t) {
  const u = 1 - t;
  return { x: u * u * p0.x + 2 * u * t * p1.x + t * t * p2.x, y: u * u * p0.y + 2 * u * t * p1.y + t * t * p2.y };
}

// Най-близката точка от пътеката: t (0..1) и разстояние.
export function nearestOnPath(path, p) {
  let best = { t: 0, d: Infinity };
  for (let i = 0; i <= 24; i++) {
    const t = i / 24;
    const q = quad(path.p0, path.p1, path.p2, t);
    const d = Math.hypot(q.x - p.x, q.y - p.y);
    if (d < best.d) best = { t, d };
  }
  return best;
}

